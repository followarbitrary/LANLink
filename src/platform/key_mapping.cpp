template <std::size_t N>
std::optional<std::uint32_t> forward(const std::array<Mapping, N>& mappings,
                                     std::uint32_t platform) {
  for (const auto& mapping : mappings) {
    if (mapping.platform == platform) return mapping.hid;
  }
  return std::nullopt;
}

template <std::size_t N>
std::optional<std::uint32_t> inverse(const std::array<Mapping, N>& mappings,
                                     std::uint32_t hid) {
  for (const auto& mapping : mappings) {
    if (mapping.hid == hid) return mapping.platform;
  }
  return std::nullopt;
}

